# ── POINT → VOXEL LABELS ─────────────────────────────────────────
def assign_voxel_labels_5(point_labels_5, inverse, n_voxels):
    """
    Assign point labels to voxels using the saved inverse mapping.

    inverse[i] = voxel index containing point i

    Therefore:

        point_labels_5
              ↓
           inverse
              ↓
        voxel labels

    Majority vote is performed for each voxel.
    """

    # ------------------------------------------------------------
    # Sort points by voxel index.
    #
    # Example:
    #
    # inverse:
    # [2, 0, 2, 1, 0]
    #
    # becomes:
    #
    # voxel 0 → points 1,4
    # voxel 1 → point 3
    # voxel 2 → points 0,2
    # ------------------------------------------------------------

    order = np.argsort(
        inverse,
        kind="stable"
    )

    inverse_sorted = inverse[order]
    labels_sorted = point_labels_5[order].astype(np.int32)

    # Find where voxel index changes
    diff = np.diff(inverse_sorted)

    splits = np.flatnonzero(diff) + 1

    starts = np.r_[0, splits]

    # Number of points belonging to each voxel
    counts = np.diff(
        np.r_[starts, len(inverse_sorted)]
    )

    # ------------------------------------------------------------
    # Majority vote
    # ------------------------------------------------------------

    # Shape:
    #     (number of voxels, 5 classes)

    hist = np.zeros(
        (n_voxels, N_CLASSES_5),
        dtype=np.int32
    )

    # For each class count how many points
    # of that class occur in each voxel.
    for c in range(N_CLASSES_5):

        class_mask = (
            labels_sorted == c
        ).astype(np.int32)

        hist[:, c] = np.add.reduceat(
            class_mask,
            starts
        )

    # Majority class
    voxel_class = np.argmax(
        hist,
        axis=1
    ).astype(np.uint8)

    # Confidence = majority points / total points
    majority_count = hist[
        np.arange(n_voxels),
        voxel_class
    ]

    voxel_conf = (
        majority_count /
        np.maximum(counts, 1)
    ).astype(np.float32)

    return voxel_class, voxel_conf


# ── CELL LABELS ──────────────────────────────────────────────────
def assign_cell_labels_5(
    features,
    voxel_class,
    voxel_conf,
    metas
):
    """
    Project voxel 5-class labels to 2D cells.

    Multiple voxels occupying the same XY cell
    are combined using point-count weighted voting.
    """

    levels_arr = features["levels"]

    pcount_arr = features[
        "point_count"
    ].astype(np.float32)

    cx_all = features["center_x"]
    cy_all = features["center_y"]

    cell_labels = {}
    cell_conf = {}

    for lv in [0, 1, 2]:

        meta = metas[lv]

        H = meta["H"]
        W = meta["W"]

        vs = meta["vox_size"]

        ix_min = meta["ix_min"]
        iy_min = meta["iy_min"]

        # Select voxels belonging to this resolution
        mask = levels_arr == lv

        if mask.sum() == 0:

            cell_labels[lv] = np.zeros(
                (H, W),
                dtype=np.uint8
            )

            cell_conf[lv] = np.zeros(
                (H, W),
                dtype=np.float32
            )

            continue

        cx = cx_all[mask]
        cy = cy_all[mask]

        vc = voxel_class[mask]
        pc = pcount_arr[mask]

        # Convert voxel center → 2D grid coordinate
        ix_rel = (
            np.floor(cx / vs).astype(np.int32)
            - ix_min
        )

        iy_rel = (
            np.floor(cy / vs).astype(np.int32)
            - iy_min
        )

        flat = (
            ix_rel * W + iy_rel
        ).astype(np.int64)

        # Group voxels belonging to same cell
        order = np.argsort(
            flat,
            kind="stable"
        )

        flat_s = flat[order]
        vc_s = vc[order]
        pc_s = pc[order]

        diff = np.diff(flat_s)

        splits = np.flatnonzero(
            diff
        ) + 1

        starts = np.r_[0, splits]

        unique_cells = flat_s[starts]

        n_occ = len(unique_cells)

        # --------------------------------------------------------
        # Weighted class histogram
        # --------------------------------------------------------

        hist_occ = np.zeros(
            (n_occ, N_CLASSES_5),
            dtype=np.float32
        )

        for c in range(N_CLASSES_5):

            class_mask = (
                vc_s == c
            ).astype(np.float32)

            weighted = (
                class_mask * pc_s
            )

            hist_occ[:, c] = np.add.reduceat(
                weighted,
                starts
            )

        cls_occ = np.argmax(
            hist_occ,
            axis=1
        ).astype(np.uint8)

        tot_occ = hist_occ.sum(
            axis=1
        )

        conf_occ = (
            hist_occ[
                np.arange(n_occ),
                cls_occ
            ]
            /
            np.maximum(tot_occ, 1)
        ).astype(np.float32)

        # --------------------------------------------------------
        # Put occupied cells into full grid
        # --------------------------------------------------------

        cls_grid = np.zeros(
            H * W,
            dtype=np.uint8
        )

        conf_grid = np.zeros(
            H * W,
            dtype=np.float32
        )

        cls_grid[unique_cells] = cls_occ

        conf_grid[unique_cells] = conf_occ

        cell_labels[lv] = cls_grid.reshape(
            H,
            W
        )

        cell_conf[lv] = conf_grid.reshape(
            H,
            W
        )

    return cell_labels, cell_conf


# ── SPARSE DATASET ───────────────────────────────────────────────
def build_sparse_5(
    grids,
    metas,
    cell_labels,
    cell_conf
):

    dataset = {}

    for lv in [0, 1, 2]:

        grid = grids[lv]

        labels = cell_labels[lv]

        conf = cell_conf[lv]

        # Occupied cells
        occ = grid[
            :,
            :,
            CH["is_occupied"]
        ].astype(bool)

        # Ignore class is removed from training dataset
        valid = (
            occ &
            (labels != IGNORE_CLASS)
        )

        if valid.sum() == 0:

            dataset[lv] = None

            continue

        ix, iy = np.where(valid)

        coords = np.stack(
            [ix, iy],
            axis=1
        ).astype(np.int32)

        feat = grid[
            ix,
            iy,
            :
        ]

        lbl = labels[
            ix,
            iy
        ]

        c = conf[
            ix,
            iy
        ]

        dataset[lv] = {
            "coords": coords,
            "features": feat,
            "labels": lbl,
            "confidence": c,
            "meta": metas[lv],
        }

    return dataset


# ── SAVE SPARSE DATASET ──────────────────────────────────────────
def save_sparse_5(
    frame_id,
    dataset
):

    arrays = {}

    for lv, d in dataset.items():

        if d is None:
            continue

        pfx = f"l{lv}_"

        arrays[pfx + "coords"] = d[
            "coords"
        ]

        arrays[pfx + "features"] = d[
            "features"
        ]

        arrays[pfx + "labels"] = d[
            "labels"
        ]

        arrays[pfx + "confidence"] = d[
            "confidence"
        ]

    path = os.path.join(
        SPARSE5_DIR,
        f"{frame_id}_sparse5.npz"
    )

    np.savez_compressed(
        path,
        **arrays
    )

    return path


