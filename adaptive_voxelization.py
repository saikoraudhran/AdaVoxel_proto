def verify_inverse(features, inverse, points):
    """
    Check inverse is consistent with stored unique_keys
    by recomputing voxel indices for a sample of points
    and confirming they match what inverse says.
    """
    errors = []

    # Check shape
    if len(inverse) != len(points):
        errors.append(
            f"inverse length {len(inverse)} "
            f"!= points length {len(points)}"
        )

    # Check range
    V = len(features["unique_keys"])
    if inverse.min() < 0 or inverse.max() >= V:
        errors.append(
            f"inverse out of range: "
            f"min={inverse.min()} max={inverse.max()} V={V}"
        )

    # Spot check: point counts via inverse should match stored
    reconstructed_counts = np.bincount(
        inverse, minlength=V
    ).astype(np.int32)
    if not np.array_equal(reconstructed_counts,
                          features["point_count"]):
        errors.append("point_count mismatch via inverse")

    return errors


